/**
 * 每日结算弹层。
 *
 * 对应原站的「📊 每日结算」底部弹层：
 *   - 标题「📊 每日结算」+ 右上角 ✕
 *   - 文案「一天结束啦，根据今天的完成情况打个分吧。」
 *   - 橙色通栏大按钮「生成今日结算」
 *   - 生成后展示分数、完成情况、评语、改进建议
 *   - 可以再点按钮让 AI 写深度复盘
 */
@Composable
fun SettleSheet(
    tasks: List<TaskEntity>,
    dateKey: String,
    existing: ReviewEntity?,
    onDismiss: () -> Unit,
    onGenerate: () -> Unit,
    onAskAi: () -> Unit = {},
    aiBusy: Boolean = false,
    modifier: Modifier = Modifier,
) {
    val palette = LocalPalette.current
    val haptics = LocalHaptics.current

    // 没生成过就先显示引导；生成过就显示结果
    val result = remember(tasks, dateKey) { SettleCalculator.calculate(tasks, dateKey) }
    var generated by remember(existing) { mutableStateOf(existing != null) }

    TopSheet(
        onDismiss = onDismiss,
        testTag = "settle_sheet",
    ) {
        Column(
            Modifier
                .fillMaxWidth()
                .padding(horizontal = 20.dp)
                .padding(bottom = 28.dp),
        ) {
            // ---------- 标题 ----------
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    "📊 每日结算",
                    style = AppText.body.copy(fontWeight = FontWeight.Bold, fontSize = 17.sp),
                    color = palette.text,
                    modifier = Modifier.weight(1f),
                )
                Box(
                    Modifier
                        .size(32.dp)
                        .clip(RoundedCornerShape(10.dp))
                        .clickable(onClick = onDismiss)
                        .testTag("settle_close"),
                    contentAlignment = Alignment.Center,
                ) {
                    Icon(
                        Icons.Outlined.Close,
                        contentDescription = "关闭",
                        tint = palette.text2,
                        modifier = Modifier.size(18.dp),
                    )
                }
            }

            Spacer(Modifier.height(12.dp))

            if (!generated) {
                // ---------- 还没生成 ----------
                Text(
                    "一天结束啦，根据今天的完成情况打个分吧。",
                    style = AppText.body,
                    color = palette.text2,
                )
                Spacer(Modifier.height(16.dp))
                PrimaryButton(
                    text = "生成今日结算",
                    onClick = {
                        haptics.perform(HapticCue.Commit)
                        generated = true
                        onGenerate()
                    },
                    modifier = Modifier.testTag("settle_generate"),
                )
            } else {
                // ---------- 生成后的结果 ----------
                val review = existing
                ScoreHeader(
                    score = review?.score ?: result.score,
                    summary = review?.summary ?: result.summary,
                )
                Spacer(Modifier.height(14.dp))
                InfoBlock("评语", review?.feedback ?: result.feedback)
                Spacer(Modifier.height(10.dp))
                InfoBlock("改进建议", review?.improvement ?: result.improvement)

                val ai = review?.aiFeedback
                if (!ai.isNullOrBlank()) {
                    Spacer(Modifier.height(10.dp))
                    InfoBlock("AI 复盘", ai)
                } else {
                    Spacer(Modifier.height(16.dp))
                    PrimaryButton(
                        text = if (aiBusy) "AI 正在写…" else "让 AI 写深度复盘",
                        enabled = !aiBusy,
                        onClick = {
                            haptics.perform(HapticCue.Tap)
                            onAskAi()
                        },
                        modifier = Modifier.testTag("settle_ai"),
                    )
                }

                Spacer(Modifier.height(10.dp))
                Text(
                    "结算记录会存进「统计」页，之后可以在那里回看",
                    style = AppText.sub,
                    color = palette.text3,
                    fontSize = 11.sp,
                )
            }
        }
    }
}

// ---------------------------------------------------------------- 小组件

@Composable
private fun ScoreHeader(score: Int, summary: String) {
    val palette = LocalPalette.current
    Row(
        Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(Dimens.radius.dp))
            .background(palette.primarySoft)
            .padding(16.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(horizontalAlignment = Alignment.CenterHorizontally) {
            Text(
                score.toString(),
                style = AppText.title.copy(fontSize = 34.sp),
                color = palette.primaryDeep,
                fontWeight = FontWeight.ExtraBold,
            )
            Text("分", style = AppText.sub, color = palette.primaryDeep)
        }
        Spacer(Modifier.size(18.dp))
        Text(
            summary,
            style = AppText.body.copy(fontWeight = FontWeight.SemiBold),
            color = palette.text,
        )
    }
}

@Composable
private fun InfoBlock(label: String, content: String) {
    val palette = LocalPalette.current
    Column(
        Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(Dimens.radiusSm.dp))
            .background(palette.surface2)
            .padding(12.dp),
    ) {
        Text(
            label,
            style = AppText.sub.copy(fontWeight = FontWeight.SemiBold),
            color = palette.text2,
        )
        Spacer(Modifier.height(4.dp))
        Text(content, style = AppText.body, color = palette.text)
    }
}

@Composable
private fun PrimaryButton(
    text: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    enabled: Boolean = true,
) {
    val palette = LocalPalette.current
    Box(
        modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(999.dp))
            .background(if (enabled) palette.primary else palette.surface2)
            .clickable(enabled = enabled, onClick = onClick)
            .padding(vertical = 14.dp),
        contentAlignment = Alignment.Center,
    ) {
        Text(
            text,
            style = AppText.body.copy(fontWeight = FontWeight.Bold),
            color = if (enabled) palette.scheme.onPrimary else palette.text3,
        )
    }
}
