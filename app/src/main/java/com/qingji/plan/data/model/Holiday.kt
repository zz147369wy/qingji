    private val ENTRIES: List<Triple<String, String, Boolean>> =
        RAW.lineSequence().mapIndexedNotNull { index, rawLine ->
            val line = rawLine.trim()
            if (line.isEmpty()) return@mapIndexedNotNull null
            val parts = line.split('|')
            if (parts.size != 3) {
                error("Holiday.kt 内置数据第 ${index + 1} 行格式不对：$line")
            }
            val (date, name, flag) = parts
            val off = when (flag) {
                "休" -> true
                "班" -> false
                else -> error("Holiday.kt 内置数据第 ${index + 1} 行标记只认「休」或「班」：$line")
            }
            Triple(date, name, off)
        }.toList()

    // associate 会让重复的日期**静默覆盖**，所以 entryCount 和 size 两个数都要能读到，
