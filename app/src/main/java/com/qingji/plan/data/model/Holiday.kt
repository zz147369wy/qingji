import com.qingji.plan.util.DateUtils
import java.time.LocalDate

/**
 * 中国大陆的**法定节假日**与**调休上班日**。
 *
 * 这是本项目**新增**的能力 —— 原网页站完全没有节假日概念（它是个纯排程工具，
 * 日历上没有农历、节气、节日，也没有「休/班」标记）。参考的是用户手机自带日历的样子。
 *
 * ## 数据从哪来
 *
 * 国务院办公厅每年年底发布下一年的《放假安排通知》，这是唯一的权威来源。
 * 这里内置的是**已经发布过的年份**，不是估算、不是推算：
 * 每个节日的放假区间和调休上班日都是通知里点名的具体日期，算法推不出来
 * （比如 2026 年春节是 2/15–2/23 放假、2/14 和 2/28 补班，这没法由规则算出）。
 *
 * 数据由 `NateScarlet/holiday-cn` 整理（该仓库逐条附了通知原文链接），
 * 抽取脚本把每一年的 JSON 拍平成下面这张表。
 *
 * ## 覆盖范围
 *
 * **2015–2026 年**，共 405 条。超出范围的年份查询返回 `null`，
 * 日历上那几天就只是普通日子 —— 不猜、不推、不报错。
 * （2027 年的安排截至本项目最后更新时还没发布，所以没有。）
 *
 * ## 为什么不读系统日历
 *
 * 用户的手机日历（vivo/iQOO 自带）确实能显示休/班，但那套数据是 **ROM 日历 App 自己写死的**，
 * 并不作为可查询的行暴露在 `CalendarContract` 里，第三方 App 读不到。
 * 而且读系统日历要 `READ_CALENDAR` 运行时权限，本工程的设计是
 * **只写不读**（见 PRD 风险 R4：App 是唯一数据源，系统日历只当展示端）。
 * 所以内置一张表反而是最准、最省事、也最符合「离线可用」的做法。
 */
data class Holiday(
    /** 通知里的节日名，如 `"春节"`。合并放假时是 `"中秋节、国庆节"` 这种 */
    val name: String,
    /** true = 放假（休），false = 调休上班（班） */
    val isOffDay: Boolean,
) {
    /** 日期旁边那个小字：`休` / `班` */
    val badge: String get() = if (isOffDay) "休" else "班"

    /**
     * 格子里显示的名字。
     *
     * 两个节日合并放假时原名是 `"中秋节、国庆节"`（**7 个字**），
     * 而一格只有约 40dp 宽、字号 8sp —— 超过 5 个字就会被省略号截掉。
     * 所以合并的场合把顿号换成间隔号，并且**去掉每段末尾的「节」**：
     * `"中秋节、国庆节"` → `"中秋·国庆"`。
     *
     * 单独一个节日**不**去「节」—— `"国庆节"` 就该是 `"国庆节"`，不是 `"国庆"`。
     *
     * 另外 2015 年那条抗战纪念日的全名有 22 个字，单独给个简称。
     * 完整正式的名字仍然在 [name] 里，没有被丢掉。
     */
    val shortName: String
        get() = when {
            name == ANNIVERSARY_2015 -> "抗战胜利70周年"
            name.contains('、') -> name.split('、').joinToString("·") { it.removeSuffix("节") }
            else -> name
        }

    companion object {
        /** 2015-09-03 那次的正式名称太长，格子里放不下 */
        const val ANNIVERSARY_2015: String = "抗日战争暨世界反法西斯战争胜利70周年纪念日"
    }
}

